def _find_first(text: str, candidates) -> str | None:
    """자막에 등장하는 사전 표제어 중 가장 앞에 나오는 것. 없으면 None."""
    found = [(text.index(word), word) for word in candidates if word in text]
    return min(found)[1] if found else None


def find_antonym_source(text: str) -> str | None:
    return _find_first(text, ANTONYMS)


def find_compound(text: str) -> str | None:
    return _find_first(text, COMPOUND_WORDS)


def pick_distractor_mimetic(answer: str) -> str:
    """정답과 다른 범주의 흉내 내는 말을 고른다.

    2지선다에서 필요한 것은 정답이 한국어에서 유일하게 옳은 단어라는 보장이 아니라,
    오답보다 명백히 낫다는 보장이다. 범주가 다르면 그 조건이 성립한다.
    사전 순서상 가장 앞의 다른 범주 단어를 골라 결정론을 유지한다.
    """
    answer_category = MIMETIC_WORDS[answer][1]
    for word, (_, category) in MIMETIC_WORDS.items():
        if category != answer_category:
            return word
    raise ValueError("다른 범주의 흉내 내는 말이 없습니다")


def pick_distractor_emotion(answer: str) -> str:
    """정답이 아닌 첫 감정. 목록 순서를 따라 결정론적으로 고른다."""
    for emotion in EMOTIONS:
        if emotion != answer:
            return emotion
    raise ValueError("다른 감정이 없습니다")

